import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
const html=readFileSync(new URL('../public/binch/da-lab.html',import.meta.url),'utf8');
assert.match(html,/<html lang="fr">/);
assert.match(html,/<meta name="viewport"/);
assert.match(html,/@media\(max-width:430px\)/);
assert.match(html,/@media\(prefers-reduced-motion:no-preference\)/);
assert.match(html,/<main id="stage" data-pair="tauren-druid"/);
assert.match(html,/aria-pressed="true"/);
for(const name of ['tauren-druid','troll-shaman','orc-warrior','elf-druid','undead-warlock','gnome-mage'])assert.ok(html.includes("'"+name+"':{"),'missing '+name+' concept');
assert.match(html,/Object\.hasOwn\(concepts,id\)/,'theme selection must be whitelisted');
assert.match(html,/\.textContent=x\[field\]/,'profile data must not be inserted as HTML');
assert.doesNotMatch(html,/(?:localStorage|fetch\(|XMLHttpRequest|sendBeacon\()/,'preview must not read player data or make requests');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1,'one standalone script expected');
new Script(scripts[0][1],{filename:'da-lab.html:inline'});
const buttons=[...html.matchAll(/data-choice="([^"]+)"/g)].map(x=>x[1]);
assert.deepEqual(buttons,['tauren-druid','troll-shaman','orc-warrior','elf-druid','undead-warlock','gnome-mage']);
assert.match(html,/Effets réduits/);
assert.match(html,/pas une vérification de leur disponibilité/);
console.log('La Binch DA pilot: 18 checks passed');
