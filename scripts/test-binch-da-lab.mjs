import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {Script} from 'node:vm';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const themes=require('../public/binch/da-themes.js');
const html=readFileSync(new URL('../public/binch/da-lab.html',import.meta.url),'utf8');
assert.match(html,/<html lang="fr">/);
assert.match(html,/<meta name="viewport"/);
assert.match(html,/@media\(max-width:430px\)/);
assert.match(html,/@media\(prefers-reduced-motion:no-preference\)/);
assert.match(html,/<main id="stage" data-pair="tauren-druid"/);
assert.match(html,/aria-pressed="true"/);
assert.match(html,/<script src="\.\/da-themes\.js"><\/script>/);
const expected=['tauren-druid','troll-shaman','orc-warrior','elf-druid','undead-warlock','gnome-mage'];
assert.deepEqual(themes.pairs,expected);
const buttons=[...html.matchAll(/data-choice="([^"]+)"/g)].map(x=>x[1]);
assert.deepEqual(buttons,expected);
for(const id of expected){
  const c=themes.resolve(id);
  assert.ok(c && c.crest && c.headline && c.material && c.signature,'missing complete concept '+id);
}
assert.equal(themes.compatibility,'unverified','artwork must never assert Forever playability');
assert.equal(themes.findPair('Tauren','Druide'),'tauren-druid');
assert.equal(themes.findPair('Mort-vivant','Démoniste'),'undead-warlock');
assert.equal(themes.findPair('Elfe','Druide'),'elf-druid');
assert.equal(themes.findPair('Gnome','Mage'),'gnome-mage');
assert.equal(themes.findPair('Gnome','Druide'),null,'unsupported art combinations receive no invented identity');
assert.equal(themes.findPair('__proto__','constructor'),null,'only whitelisted pair identifiers are allowed');
assert.equal(themes.resolve('__proto__'),null);
assert.equal(themes.resolve('unknown'),null);
assert.match(html,/themes\.resolve\(id\)/);
assert.match(html,/\.textContent=x\[field\]/);
assert.doesNotMatch(html,/(?:localStorage|fetch\(|XMLHttpRequest|sendBeacon\()/,'preview must not read player data or make requests');
assert.doesNotMatch(readFileSync(new URL('../public/binch/da-themes.js',import.meta.url),'utf8'),/(?:localStorage|fetch\(|XMLHttpRequest|sendBeacon\()/,'registry must not read player data or make requests');
const scripts=[...html.matchAll(/<script(?:\s[^>]*)?>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length,1,'one standalone inline controller expected');
new Script(scripts[0][1],{filename:'da-lab.html:inline'});
assert.match(html,/Effets réduits/);
assert.match(html,/pas une vérification de leur disponibilité/);
console.log('La Binch DA pilot: isolated registry and six themes passed');
